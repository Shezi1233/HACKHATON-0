class AuditLoggingSystem:
    """System for comprehensive audit logging"""

    def __init__(self, vault_path: str):
        self.vault_path = Path(vault_path)
        self.logs_path = self.vault_path / "Logs"
        self.logs_path.mkdir(exist_ok=True)

        # Set up Python logging
        logging.basicConfig(
            level=logging.INFO,
            format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
            handlers=[
                logging.FileHandler(self.logs_path / f"audit_{datetime.now().strftime('%Y%m%d')}.log"),
                logging.StreamHandler()
            ]
        )
        self.logger = logging.getLogger(self.__class__.__name__)

    def log_action(self, action_type: str, actor: str, target: str, parameters: Dict[str, Any],
                   approval_status: str = "auto", approved_by: str = "system", result: str = "success"):
        """Log an action performed by the AI Employee"""
        log_entry = {
            "timestamp": datetime.now().isoformat(),
            "action_type": action_type,
            "actor": actor,
            "target": target,
            "parameters": parameters,
            "approval_status": approval_status,
            "approved_by": approved_by,
            "result": result
        }

        # Write to JSON log file
        log_file = self.logs_path / f"actions_{datetime.now().strftime('%Y%m%d')}.json"
        try:
            # Read existing logs if file exists
            if log_file.exists():
                with open(log_file, 'r') as f:
                    existing_logs = json.load(f)
            else:
                existing_logs = []
        except json.JSONDecodeError:
            existing_logs = []

        # Append new log and write back
        existing_logs.append(log_entry)
        with open(log_file, 'w') as f:
            json.dump(existing_logs, f, indent=2)

        # Also write a markdown summary
        self._write_markdown_log_summary(log_entry)

    def _write_markdown_log_summary(self, log_entry: Dict[str, Any]):
        """Write a markdown summary of the action log"""
        summary_file = self.logs_path / f"actions_{datetime.now().strftime('%Y%m%d')}.md"
        summary_content = f"""
## Action Log - {datetime.now().strftime('%Y-%m-%d')}

**Timestamp:** {log_entry['timestamp']}
**Action Type:** {log_entry['action_type']}
**Actor:** {log_entry['actor']}
**Target:** {log_entry['target']}
**Parameters:** {json.dumps(log_entry['parameters'], indent=2)}
**Approval Status:** {log_entry['approval_status']}
**Approved By:** {log_entry['approved_by']}
**Result:** {log_entry['result']}

---
"""

        # Append to the markdown file
        with open(summary_file, 'a') as f:
            f.write(summary_content)


