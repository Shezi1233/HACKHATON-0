    def _get_completed_tasks(self, start_date: datetime, end_date: datetime) -> List[Dict]:
        """Get completed tasks from the Done folder"""
        completed_tasks = []
        done_path = self.vault_path / "Done"

        if done_path.exists():
            for file_path in done_path.glob("*.md"):
                try:
                    # Try to get the creation/modification date from the filename or content
                    file_stat = file_path.stat()
                    file_date = datetime.fromtimestamp(file_stat.st_mtime)

                    # Check if the file was modified within our date range
                    if start_date <= file_date.date() <= end_date.date():
                        content = file_path.read_text()
                        # Extract task summary from the file content
                        first_line = content.split('\n')[0] if content else file_path.stem
                        completed_tasks.append({
                            'title': first_line.replace('#', '').strip(),
                            'filename': file_path.name,
                            'completed_date': file_date.isoformat()
                        })
                except Exception as e:
                    self.logger.error(f"Error reading completed task {file_path}: {e}")

        return completed_tasks[:20]  # Limit to 20 most recent

    def _get_bottlenecks(self, start_date: datetime, end_date: datetime) -> List[Dict]:
        """Get identified bottlenecks from the system"""
        bottlenecks = []

        # Check for tasks that took longer than expected
        plans_path = self.vault_path / "Plans"
        if plans_path.exists():
            for file_path in plans_path.glob("*.md"):
                try:
                    content = file_path.read_text()
                    # Look for signs of task delays or issues
                    if any(keyword in content.lower() for keyword in ['delay', 'blocked', 'stuck', 'waiting']):
                        bottlenecks.append({
                            'task': file_path.stem,
                            'issue': 'Task appears to be delayed or blocked based on plan status',
                            'file': str(file_path)
                        })
                except Exception as e:
                    self.logger.error(f"Error reading plan {file_path}: {e}")

        # Check for approval requests that are pending too long
        pending_approval_path = self.vault_path / "Pending_Approval"
        if pending_approval_path.exists():
            for file_path in pending_approval_path.glob("*.md"):
                try:
                    file_stat = file_path.stat()
                    file_age = datetime.now() - datetime.fromtimestamp(file_stat.st_ctime)

                    # If approval has been pending for more than 2 days, flag as bottleneck
                    if file_age.days > 2:
                        bottlenecks.append({
                            'task': file_path.stem,
                            'issue': f'Approval pending for {file_age.days} days',
                            'file': str(file_path)
                        })
                except Exception as e:
                    self.logger.error(f"Error checking approval age {file_path}: {e}")

        return bottlenecks[:10]  # Limit to 10 most significant

