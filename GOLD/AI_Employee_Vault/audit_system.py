    def _get_upcoming_deadlines(self) -> str:
        """Get upcoming deadlines and important dates"""
        # Check Business_Goals.md for project deadlines
        business_goals_path = self.vault_path / "Business_Goals.md"
        deadlines = []

        if business_goals_path.exists():
            content = business_goals_path.read_text()
            # Look for due dates in the business goals
            import re
            # Find patterns like "Due Mar 31", "Due April 30", etc.
            date_patterns = [
                r'Due\s+(\w+\s+\d+)',  # Due Mar 31
                r'Due\s+(\d+/\d+)',    # Due 03/31
                r'Due\s+(\d{4}-\d{2}-\d{2})'  # Due 2023-03-31
            ]

            for pattern in date_patterns:
                matches = re.findall(pattern, content, re.IGNORECASE)
                for match in matches:
                    try:
                        # Attempt to parse the date
                        if '/' in match:
                            deadline_date = datetime.strptime(match, '%m/%d')
                            deadline_date = deadline_date.replace(year=datetime.now().year)
                        elif '-' in match:
                            deadline_date = datetime.strptime(match, '%Y-%m-%d')
                        else:
                            # Month day format like "Mar 31"
                            deadline_date = datetime.strptime(f"{match} {datetime.now().year}", '%b %d %Y')

                        # Only include deadlines within the next 30 days
                        if 0 <= (deadline_date - datetime.now()).days <= 30:
                            deadlines.append({
                                'event': f'Project deadline',
                                'date': deadline_date.strftime('%Y-%m-%d'),
                                'days_until': (deadline_date - datetime.now()).days
                            })
                    except:
                        continue

        if not deadlines:
            return "No upcoming deadlines identified in the next 30 days.\n\n"

        lines = ["### Upcoming Deadlines\n"]
        for deadline in deadlines:
            lines.append(f"- **{deadline['event']}**: {deadline['date']} ({deadline['days_until']} days)")

        return '\n'.join(lines) + "\n"

