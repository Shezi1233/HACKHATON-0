    def generate_weekly_ceo_briefing(self) -> str:
        """Generate the comprehensive weekly CEO briefing with accounting data"""
        # Calculate the week range (Sunday to Saturday)
        today = datetime.now()
        start_of_week = today - timedelta(days=today.weekday() + 1)  # Last Sunday
        end_of_week = start_of_week + timedelta(days=6)  # Following Saturday

        # Format dates for filename
        week_start_str = start_of_week.strftime("%Y-%m-%d")
        week_end_str = end_of_week.strftime("%Y-%m-%d")

        # Generate the briefing content
        briefing_content = self._generate_briefing_content(start_of_week, end_of_week)

        # Write to file
        briefing_filename = f"{week_start_str}_Weekly_CEO_Briefing.md"
        briefing_path = self.briefings_path / briefing_filename

        briefing_path.write_text(briefing_content)

        self.logger.info(f"Weekly CEO briefing generated: {briefing_path}")
        return str(briefing_path)

